#!/usr/bin/env python3
"""Independent re-proof of the ZigZag "champion" (variant B) Sharpe — user request 2026-11-10.

Rebuilds EVERYTHING from the raw Switch H1 bars (no cached probabilities):
  1. walk-forward probabilities: pooled HistGradientBoosting (gold + EURUSDs/GBPUSDs/USDJPYs),
     refit monthly on the trailing 20,000 bars per series, labels built on data truncated at the
     cut, last TOL+1 bars purged. Checked against the cached §3dg probabilities (correlation).
  2. variant B as deployed on Darwinex/FTMO: fire P >= 0.60 on a closed H1 bar -> BUY next open
     + $0.25 spread; stop 3 ATR(14) below; stop trails 3 ATR under the highest high (applies from
     the next bar); TP at entry + 4.3 x (3 ATR); max hold 120 bars; one position at a time;
     long swap -6%/yr. Entries are generated by variant B's OWN exits (not the §3dr fixed set).
  3. statistics: trades/week, win %, avg R, Sharpe (daily, sqrt 252), per-year, maxDD,
     stationary block-bootstrap 95% CI of Sharpe, random-timing null (circular shift of the fire
     array, 300 draws), buy & hold gold over the same days, 2x-spread stress.

    python scripts/v5_zigzag_champion_reproof.py
"""
from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.v5_zigzag_live_wf import (OUT as WF, RISK, SPREAD, START, SWAP, SYMS, THR, TRAIL,  # noqa: E402
                                       MAX_HOLD, load, probs, sharpe)
from scripts.v5_zigzag_signal import LEAK_MAX, atr, intrabar_leak  # noqa: E402

OUT = ROOT / "data" / "v5_runs" / "zigzag_reproof"
TP_R = 4.3


def run(g, pr, tp_r=TP_R, spread=SPREAD, fire=None):
    o, h, l = (g[x].to_numpy() for x in ("open", "high", "low"))
    a, t = atr(g).to_numpy(), g.index
    f = (np.isfinite(pr) & (pr >= THR)) if fire is None else fire
    f = f & (t >= START) & np.isfinite(a)
    trades, i, n = [], 0, len(g)
    while i < n - 1:
        if not f[i]:
            i += 1
            continue
        s = i + 1
        e = o[s] + spread
        risk = TRAIL * a[i]
        sl, best = e - risk, e
        tp = e + tp_r * risk if tp_r else np.inf
        j, px, why = n - 1, o[-1], "open"
        for j in range(s, n):
            if l[j] <= sl:                                    # stop first if both touched
                px, why = min(sl, o[j]), "stop"
                break
            if h[j] >= tp:
                px, why = max(tp, o[j]), "tp"
                break
            if j - s >= MAX_HOLD:
                px, why = o[j], "time"
                break
            best = max(best, h[j])
            sl = max(sl, best - TRAIL * a[j])
        days = (t[j] - t[s]).total_seconds() / 86400
        pnl = px - e + e * SWAP * days / 365
        trades.append((t[s], t[j], pnl / risk, j - s, why))
        i = j + 1 if j > i else i + 1                         # flat again: may re-enter after exit
    tr = pd.DataFrame(trades, columns=["t_in", "t_out", "R", "bars", "exit"])
    days = pd.date_range(START.normalize(), t[-1].normalize(), freq="D")
    ret = pd.Series(0.0, index=days)
    for r in tr.itertuples():
        ret[r.t_out.normalize()] += RISK * r.R
    return tr, ret[ret.index.dayofweek < 5], f


def block_boot(r, n=2000, blk=20, seed=7):
    x, rng, out = r.to_numpy(), np.random.default_rng(seed), []
    L = len(x)
    for _ in range(n):
        idx = np.concatenate([np.arange(s, s + blk) % L for s in rng.integers(0, L, L // blk + 1)])[:L]
        y = x[idx]
        out.append(y.mean() / y.std() * np.sqrt(252) if y.std() > 0 else 0)
    return np.percentile(out, [2.5, 50, 97.5])


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    gold = load("XAUUSDs")
    aux = {s: load(s) for s in SYMS[1:]}
    aux = {s: d for s, d in aux.items() if intrabar_leak(d) <= LEAK_MAX}
    cache = OUT / "probs.csv"
    if cache.exists():
        p = pd.read_csv(cache, index_col=0, parse_dates=True).iloc[:, 0]
    else:
        p = probs(gold, aux)
        p.to_csv(cache)
    old = pd.read_csv(WF / "probs.csv", index_col=0, parse_dates=True).iloc[:, 0]
    both = pd.concat([p, old], axis=1).dropna()
    pr = p.reindex(gold.index).to_numpy()

    tr, ret, f = run(gold, pr)
    eq = (1 + ret).cumprod()
    dd = (1 - eq / eq.cummax()).max()
    yrs = len(ret) / 252
    weeks = (gold.index[-1] - START).days / 7
    lo, med, hi = block_boot(ret)
    rng = np.random.default_rng(13)
    fires = np.isfinite(pr) & (pr >= THR)
    nl = np.array([sharpe(run(gold, pr, fire=np.roll(fires, int(k)))[1])
                   for k in rng.integers(500, len(fires) - 500, 300)])
    gd = gold[gold.index >= START].close.resample("D").last().dropna()
    gr = gd.pct_change().dropna() + SWAP / 252
    gr = gr[gr.index.dayofweek < 5]
    by = {y: (len(x), round(x.R.sum(), 1)) for y, x in tr.groupby(tr.t_out.dt.year)}
    sy = {y: round(sharpe(x), 2) for y, x in ret.groupby(ret.index.year)}
    wk = tr.groupby(tr.t_in.dt.to_period("W")).size().reindex(
        pd.period_range(START, gold.index[-1], freq="W"), fill_value=0)
    w, L = tr.R[tr.R > 0], tr.R[tr.R <= 0]
    lines = [
        f"ZigZag variant B re-proof, Switch XAUUSDs H1 {START:%Y-%m-%d} -> {gold.index[-1]} ({weeks:.0f} weeks)",
        f"probabilities rebuilt from scratch: {int(np.isfinite(pr).sum()):,} scored bars, corr vs cached §3dg "
        f"{both.corr().iloc[0, 1]:.4f}; fire rate {100 * fires[gold.index >= START].mean():.1f}% of H1 bars",
        f"trades {len(tr)} = {len(tr) / weeks:.2f}/week (median week {wk.median():.0f}, max {wk.max()}, "
        f"weeks with 0 trades {100 * (wk == 0).mean():.0f}%)",
        f"win {100 * (tr.R > 0).mean():.1f}%  avg win {w.mean():+.2f}R  avg loss {L.mean():+.2f}R  "
        f"expectancy {tr.R.mean():+.3f}R/trade  total {tr.R.sum():+.1f}R",
        f"exits: {tr.exit.value_counts().to_dict()}  median hold {tr.bars.median():.0f}h, "
        f"time in market {100 * tr.bars.sum() / ((gold.index >= START).sum()):.0f}%",
        f"at 0.25% risk: {100 * (eq.iloc[-1] - 1):+.2f}% ({100 * (eq.iloc[-1] ** (1 / yrs) - 1):+.2f}%/yr), "
        f"maxDD {100 * dd:.2f}%",
        f"SHARPE {sharpe(ret):+.2f}   block-bootstrap 95% CI [{lo:+.2f}, {hi:+.2f}]",
        f"per year Sharpe {sy}   trades/R by year {by}",
        f"2x spread: {sharpe(run(gold, pr, spread=2 * SPREAD)[1]):+.2f}   no TP: {sharpe(run(gold, pr, tp_r=0)[1]):+.2f}",
        f"random timing (same fire count, circular shift, 300): median {np.median(nl):+.2f}, "
        f"95th {np.percentile(nl, 95):+.2f}, p {(nl >= sharpe(ret)).mean():.3f}",
        f"hold gold same days (with swap): {100 * ((1 + gr).prod() - 1):+.1f}%, Sharpe {sharpe(gr):+.2f}, "
        f"daily corr with ZigZag {pd.concat([ret, gr], axis=1).dropna().corr().iloc[0, 1]:+.2f}",
    ]
    txt = "\n".join(lines)
    print(txt)
    (OUT / "report.txt").write_text(txt + "\n")
    tr.to_csv(OUT / "trades.csv", index=False)


if __name__ == "__main__":
    sys.exit(main())
